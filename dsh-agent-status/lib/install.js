/**
 * Pure helpers for the installer/uninstaller. Kept free of filesystem access
 * so they can be unit-tested.
 */

export const PACKAGE_NAME = 'dsh-agent-status'

const MARK_START = '# >>> dsh-agent-status:managed'
const MARK_END = '# <<< dsh-agent-status:managed'
const BLOCK_RE = /# >>> dsh-agent-status:managed[\s\S]*?# <<< dsh-agent-status:managed[ \t]*\r?\n?/u

/** @param {boolean} condition */
const on = (condition) => (condition ? 'true' : 'false')

/**
 * Render the managed YAML block written into the profile's cordis.patch.yml.
 * @param {Record<string, any>} config
 * @returns {string}
 */
export function renderPatchBlock(config) {
  return [
    `${MARK_START} (generated by scripts/install.mjs; do not edit; remove with scripts/uninstall.mjs)`,
    '- id: dsh-agent-status',
    '  name: dsh-agent-status',
    '  config:',
    `    token: ${JSON.stringify(String(config.token ?? ''))}`,
    `    port: ${Number(config.port ?? 0)}`,
    `    theme: ${JSON.stringify(String(config.theme ?? 'neon'))}`,
    `    screenTheme: ${JSON.stringify(String(config.screenTheme ?? 'neon'))}`,
    `    position: ${JSON.stringify(String(config.position ?? 'bottom-right'))}`,
    `    visible: ${on(config.visible !== false)}`,
    `    screenButton: ${on(config.screenButton !== false)}`,
    `    screenLanding: ${JSON.stringify(String(config.screenLanding ?? 'hud'))}`,
    `    screenWindow: ${JSON.stringify(String(config.screenWindow ?? 'tab'))}`,
    `    waitingAfterMs: ${Number(config.waitingAfterMs ?? 15000)}`,
    `    doneHoldMs: ${Number(config.doneHoldMs ?? 6000)}`,
    `    pollMs: ${Number(config.pollMs ?? 800)}`,
    MARK_END,
  ].join('\n')
}

/** @param {string} text */
export function hasPatchBlock(text) {
  return BLOCK_RE.test(text)
}

/**
 * Insert or replace the managed block, leaving the user's other entries intact.
 * @param {string} text current cordis.patch.yml
 * @param {Record<string, any>} config
 * @returns {string}
 */
export function upsertPatch(text, config) {
  const source = typeof text === 'string' ? text : ''
  const block = renderPatchBlock(config)
  if (BLOCK_RE.test(source)) {
    return source.replace(BLOCK_RE, `${block}\n`)
  }
  // An untouched patch layer is literally `[]`; appending a sequence after it
  // would produce invalid YAML (`[] - id: ...`).
  let base = source
  while (/^[ \t]*\[\][ \t]*\r?\n?/mu.test(base)) {
    base = base.replace(/^[ \t]*\[\][ \t]*\r?\n?/mu, '')
  }
  const trimmed = base.trimEnd()
  if (trimmed === '') return `${block}\n`
  return `${trimmed}\n\n${block}\n`
}

/**
 * Remove the managed block; keep a valid YAML document (defaults to `[]`).
 * @param {string} text
 * @returns {string}
 */
export function removePatch(text) {
  const source = typeof text === 'string' ? text : ''
  const without = source.replace(BLOCK_RE, '').replace(/\n{3,}/gu, '\n\n').trim()
  return without === '' ? '[]\n' : `${without}\n`
}

/**
 * Read scalar values back out of the managed block (used to keep a token stable on reinstall).
 * @param {string} text
 * @returns {Record<string, string|number|boolean>}
 */
export function readPatchBlock(text) {
  const match = typeof text === 'string' ? text.match(BLOCK_RE) : null
  if (match === null) return {}
  const result = {}
  for (const line of match[0].split(/\r?\n/u)) {
    const pair = /^[ \t]+([a-zA-Z][\w]*):[ \t]*(.+?)[ \t]*$/u.exec(line)
    if (pair === null) continue
    const [, key, raw] = pair
    if (key === 'id' || key === 'name') continue
    let value = raw
    if (/^".*"$/u.test(raw)) {
      try {
        value = JSON.parse(raw)
      } catch {
        value = raw.slice(1, -1)
      }
    } else if (raw === 'true' || raw === 'false') {
      value = raw === 'true'
    } else if (/^-?\d+$/u.test(raw)) {
      value = Number(raw)
    }
    result[key] = value
  }
  return result
}

/**
 * Add the link dependency and bundle entry without touching unrelated fields.
 * @param {any} pkg parsed profile package.json
 * @param {{ linkSpec: string, bundle?: string }} options
 * @returns {{ json: any, changed: boolean }}
 */
export function mergeProfilePackage(pkg, { linkSpec, bundle = PACKAGE_NAME }) {
  const before = JSON.stringify(pkg)
  const next = JSON.parse(JSON.stringify(pkg ?? {}))
  next.dependencies = next.dependencies ?? {}
  next.dependencies[PACKAGE_NAME] = linkSpec
  next.dsh = next.dsh ?? {}
  next.dsh.profile = next.dsh.profile ?? {}
  next.dsh.profile.bundles = Array.isArray(next.dsh.profile.bundles)
    ? next.dsh.profile.bundles
    : []
  if (!next.dsh.profile.bundles.includes(bundle)) next.dsh.profile.bundles.push(bundle)
  return { json: next, changed: JSON.stringify(next) !== before }
}

/**
 * Remove dependency and bundle entry for a surgical uninstall (backup missing).
 * @param {any} pkg
 * @returns {{ json: any, changed: boolean }}
 */
export function removeProfilePackage(pkg) {
  const before = JSON.stringify(pkg)
  const next = JSON.parse(JSON.stringify(pkg ?? {}))
  if (next.dependencies && typeof next.dependencies === 'object') {
    delete next.dependencies[PACKAGE_NAME]
  }
  const bundles = next.dsh?.profile?.bundles
  if (Array.isArray(bundles)) {
    next.dsh.profile.bundles = bundles.filter((name) => name !== PACKAGE_NAME)
  }
  return { json: next, changed: JSON.stringify(next) !== before }
}
